"""Bake the exhibit HUD labels into one texture for Web and WeChat."""

import json
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont


ROOT = Path(__file__).resolve().parents[1]
MEDIA = ROOT / "media/cyber-beast/packaged/ui"
HUD = ROOT / "src/game/apps/cyber-beast/hud"
LABELS = {
    "gallery": ("赛博生物展厅", "msyhbd.ttc", 14),
    "title": ("RIFT HOUND", "bahnschrift.ttf", 58),
    "specimen": ("裂隙猎犬", "msyh.ttc", 17),
    "wraithTitle": ("NEON WRAITH", "bahnschrift.ttf", 50),
    "wraithSpecimen": ("霓虹异骸", "msyh.ttc", 17),
    "orbit": ("拖动环绕", "msyh.ttc", 13),
    "pause": ("暂停转台", "msyhbd.ttc", 13),
    "play": ("启动转台", "msyhbd.ttc", 13),
    "reset": ("复位视角", "msyhbd.ttc", 13),
    "walk": ("原地踏步", "msyhbd.ttc", 13),
    "stop": ("停止踏步", "msyhbd.ttc", 13),
    "switch": ("切换怪兽", "msyhbd.ttc", 13),
}


def main():
    atlas = Image.new("RGBA", (768, 384))
    draw = ImageDraw.Draw(atlas)
    frames = {}
    x = y = 2
    row_height = 0
    for key, (text, filename, font_size) in LABELS.items():
        font = ImageFont.truetype(filename, font_size * 2)
        left, top, right, bottom = draw.textbbox((0, 0), text, font=font)
        width = right - left + 4
        height = bottom - top + 4
        if x + width > atlas.width:
            x = 2
            y += row_height + 2
            row_height = 0
        draw.text((x + 2 - left, y + 2 - top), text, font=font, fill="white")
        frames[key] = [x, y, width, height]
        x += width + 2
        row_height = max(row_height, height)

    MEDIA.mkdir(parents=True, exist_ok=True)
    atlas.crop((0, 0, atlas.width, y + row_height + 2)).save(MEDIA / "labels.png", optimize=True)
    HUD.joinpath("labelFrames.ts").write_text(
        "/* Generated by scripts/build-cyber-beast-labels.py. */\n"
        f"export const labelFrames = {json.dumps(frames, indent=2)} as const;\n",
        encoding="utf-8",
    )


if __name__ == "__main__":
    main()
