"""Bake the Drift Era HUD glyphs and a short interaction chime for WeChat."""

import json
import math
from pathlib import Path
import re
import struct
import wave

from PIL import Image, ImageDraw, ImageFont


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "src/game/apps/drift-era"
MEDIA = ROOT / "media/drift-era/packaged"
CELL_SIZE = 40
COLUMNS = 16

copy = "".join((SOURCE / name).read_text(encoding="utf-8") for name in ("routes.ts", "game.ts", "hud/driftHud.ts"))
characters = "".join(map(chr, range(33, 127))) + "".join(re.findall(r"[^\x00-\x7f\s]", copy))
glyphs = "".join(dict.fromkeys(characters))
rows = (len(glyphs) + COLUMNS - 1) // COLUMNS
atlas = Image.new("RGBA", (CELL_SIZE * COLUMNS, CELL_SIZE * rows))
draw = ImageDraw.Draw(atlas)
font = ImageFont.truetype("msyh.ttc", 30)
for index, glyph in enumerate(glyphs):
    x = index % COLUMNS * CELL_SIZE + CELL_SIZE / 2
    y = index // COLUMNS * CELL_SIZE + CELL_SIZE / 2
    left, top, right, bottom = draw.textbbox((0, 0), glyph, font=font)
    draw.text((x - (left + right) / 2, y - (top + bottom) / 2), glyph, font=font, fill="white")

(MEDIA / "ui").mkdir(parents=True, exist_ok=True)
atlas.save(MEDIA / "ui/glyphs.png", optimize=True)
(SOURCE / "hud/glyphs.ts").write_text(
    "/* Generated by scripts/build-drift-assets.py. */\n"
    f"export const cellSize = {CELL_SIZE};\n"
    f"export const columns = {COLUMNS};\n"
    f"export const glyphs = {json.dumps(glyphs, ensure_ascii=False)};\n",
    encoding="utf-8",
)

rate = 16000
duration = .17
samples = bytearray()
for index in range(int(rate * duration)):
    t = index / rate
    envelope = min(1, t / .013) * (1 - t / duration) ** 2
    phase = math.tau * (400 * t + 340 * t * t)
    sample = math.asin(math.sin(phase)) * 1600 * envelope
    samples += struct.pack("<h", round(sample))

(MEDIA / "audio").mkdir(exist_ok=True)
with wave.open(str(MEDIA / "audio/chime.wav"), "wb") as audio:
    audio.setparams((1, 2, rate, 0, "NONE", "not compressed"))
    audio.writeframes(samples)
