"""Bake the text used by the Tidal Harbor Pixi HUD for the WeChat runtime."""

import json
from pathlib import Path
import re

from PIL import Image, ImageDraw, ImageFont


ROOT = Path(__file__).resolve().parents[1]
APP = ROOT / "src/game/apps/tidal-harbor"
MEDIA = ROOT / "media/tidal-harbor/packaged/ui"
CELL = 40
COLUMNS = 16

copy = "".join((APP / name).read_text(encoding="utf-8") for name in ("content.ts", "hud/hud.ts"))
characters = "L1234567890" + "".join(re.findall(r"[^\x00-\x7f\s]", copy))
glyphs = "".join(dict.fromkeys(characters))
rows = (len(glyphs) + COLUMNS - 1) // COLUMNS
atlas = Image.new("RGBA", (CELL * COLUMNS, CELL * rows))
draw = ImageDraw.Draw(atlas)
font = ImageFont.truetype("msyhbd.ttc", 30)
for index, glyph in enumerate(glyphs):
    x = index % COLUMNS * CELL + CELL / 2
    y = index // COLUMNS * CELL + CELL / 2
    left, top, right, bottom = draw.textbbox((0, 0), glyph, font=font)
    draw.text((x - (left + right) / 2, y - (top + bottom) / 2), glyph, fill="white", font=font)

MEDIA.mkdir(parents=True, exist_ok=True)
atlas.save(MEDIA / "glyphs.png", optimize=True)
(APP / "hud/glyphs.ts").write_text(
    "/* Generated by scripts/build-harbor-glyphs.py. */\n"
    f"export const cell = {CELL};\n"
    f"export const columns = {COLUMNS};\n"
    f"export const glyphs = {json.dumps(glyphs, ensure_ascii=False)};\n",
    encoding="utf-8",
)
