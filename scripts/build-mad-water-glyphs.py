import re
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont


root = Path(__file__).resolve().parent.parent
app = root / 'src/game/apps/mad-water-haven'
glyphs = ''.join(sorted(set(re.findall(r'[\u4e00-\u9fff·]', (app / 'content.ts').read_text(encoding='utf-8')))))
cell, columns = 64, 8
atlas = Image.new('RGBA', (cell * columns, cell * ((len(glyphs) + columns - 1) // columns)))
draw = ImageDraw.Draw(atlas)
font = ImageFont.truetype('C:/Windows/Fonts/msyhbd.ttc', 46)
for i, glyph in enumerate(glyphs):
    x = i % columns * cell
    y = i // columns * cell
    left, top, right, bottom = draw.textbbox((0, 0), glyph, font=font)
    draw.text((x + (cell - left - right) / 2, y + (cell - top - bottom) / 2), glyph, font=font, fill='white')

out = root / 'media/mad-water-haven/packaged/ui'
out.mkdir(parents=True, exist_ok=True)
atlas.save(out / 'glyphs.png', optimize=True)
(app / 'hud/glyphs.ts').write_text(
    f'// Generated by scripts/build-mad-water-glyphs.py.\n'
    f'export const glyphs = \'{glyphs}\';\nexport const cell = {cell};\nexport const columns = {columns};\n',
    encoding='utf-8'
)
