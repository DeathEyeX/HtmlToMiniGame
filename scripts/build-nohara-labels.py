"""Build the house app's HUD glyph page with Windows Microsoft YaHei."""

import json
import re
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont


ROOT = Path(__file__).resolve().parents[1]
APP = ROOT / "src/game/apps/nohara-house"
MEDIA = ROOT / "media/nohara-house/packaged/ui"
CELL = 48
COLUMNS = 12

copy = (APP / "rooms.ts").read_text(encoding="utf-8")
glyphs = "".join(dict.fromkeys(re.findall(r"[\u3400-\u9fff·]", copy)))
rows = (len(glyphs) + COLUMNS - 1) // COLUMNS
image = Image.new("RGBA", (COLUMNS * CELL, rows * CELL))
draw = ImageDraw.Draw(image)
font = ImageFont.truetype("msyhbd.ttc", 36)
for index, glyph in enumerate(glyphs):
    x = index % COLUMNS * CELL + CELL / 2
    y = index // COLUMNS * CELL + CELL / 2
    left, top, right, bottom = draw.textbbox((0, 0), glyph, font=font)
    draw.text((x - (left + right) / 2, y - (top + bottom) / 2), glyph, font=font, fill="white")

MEDIA.mkdir(parents=True, exist_ok=True)
image.save(MEDIA / "labels.png", optimize=True)
(APP / "hud/labelGlyphs.ts").write_text(
    "/* Generated by scripts/build-nohara-labels.py. */\n"
    f"export const labelGlyphs = {json.dumps(glyphs, ensure_ascii=False)};\n"
    f"export const labelCell = {CELL};\n"
    f"export const labelColumns = {COLUMNS};\n",
    encoding="utf-8",
)
