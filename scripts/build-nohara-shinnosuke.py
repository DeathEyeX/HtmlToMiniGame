# Draw the curves at 4x resolution before filtering the RGBA edges.
SIZE = 256
SCALE = 4
INK = "#29212a"
SKIN = "#fcc5a2"
RED = "#e94046"
YELLOW = "#ffd24a"
image = Image.new("RGBA", (SIZE * SCALE, SIZE * SCALE))
draw = ImageDraw.Draw(image)


def shape(start, curves, color, outline=3.5):
    points = [start]
    for x1, y1, x2, y2, x3, y3 in curves:
        x0, y0 = points[-1]
        for i in range(1, 25):
            t = i / 24
            s = 1 - t
            points.append((
                s**3 * x0 + 3 * s**2 * t * x1 + 3 * s * t**2 * x2 + t**3 * x3,
                s**3 * y0 + 3 * s**2 * t * y1 + 3 * s * t**2 * y2 + t**3 * y3,
            ))
    pixels = [(round(x * SCALE), round(y * SCALE)) for x, y in points]
    draw.polygon(pixels, fill=color)
    if outline:
        draw.line(pixels + pixels[:1], fill=INK, width=round(outline * SCALE), joint="curve")


def ellipse(box, color):
    draw.ellipse(tuple(round(n * SCALE) for n in box), fill=color)


