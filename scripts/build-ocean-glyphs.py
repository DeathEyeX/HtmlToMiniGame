"""Bake the Ocean Shelter HUD text into a PNG for the WeChat renderer."""

import json
import re
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "src/game/apps/ocean-shelter"
MEDIA = ROOT / "media/ocean-shelter/packaged/ui"
CELL = 40
COLUMNS = 16

strings = "".join(
    (SOURCE / file).read_text(encoding="utf-8")
    for file in ("content.ts", "hudCopy.ts")
)
characters = "0123456789AB·×‹…" + "".join(re.findall(r"[^\x00-\x7f\s]", strings))
glyphs = "".join(dict.fromkeys(characters))
atlas = Image.new("RGBA", (CELL * COLUMNS, CELL * ((len(glyphs) + COLUMNS - 1) // COLUMNS)))
draw = ImageDraw.Draw(atlas)
font = ImageFont.truetype("simsun.ttc", 32)
for index, glyph in enumerate(glyphs):
    x = index % COLUMNS * CELL + CELL // 2
    y = index // COLUMNS * CELL + CELL // 2
    left, top, right, bottom = draw.textbbox((0, 0), glyph, font=font)
    draw.text((x - (left + right) / 2, y - (top + bottom) / 2), glyph, font=font, fill="white")

atlas.save(MEDIA / "ui-glyphs.png", optimize=True)
(SOURCE / "hudGlyphs.ts").write_text(
    "/* Generated by scripts/build-ocean-glyphs.py. */\n"
    f"export const glyphs = {json.dumps(glyphs, ensure_ascii=False)};\n",
    encoding="utf-8",
)
