"""Bake the outpost HUD labels for the Web and WeChat builds."""

import json
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
LABELS = {
    "title": ("A-03 · 前线前哨站", 22),
    "hint": ("单指旋转 · 双指缩放和平移", 13),
    "iso": ("斜前方", 13),
    "front": ("正面", 13),
    "side": ("侧面", 13),
    "back": ("背面", 13),
    "top": ("俯视", 13),
    "spin": ("自动旋转", 13),
    "stop": ("停止旋转", 13),
    "wire": ("线框", 13),
    "solid": ("实体", 13),
    "zoomIn": ("放大", 13),
    "zoomOut": ("缩小", 13),
}


def main():
    atlas = Image.new("RGBA", (640, 256))
    draw = ImageDraw.Draw(atlas)
    frames = {}
    x = y = 2
    row_height = 0
    for key, (text, size) in LABELS.items():
        font = ImageFont.truetype("msyhbd.ttc", size * 2)
        left, top, right, bottom = draw.textbbox((0, 0), text, font=font)
        width, height = right - left + 4, bottom - top + 4
        if x + width > atlas.width:
            x = 2
            y += row_height + 2
            row_height = 0
        draw.text((x + 2 - left, y + 2 - top), text, font=font, fill="white")
        frames[key] = [x, y, width, height, text]
        x += width + 2
        row_height = max(row_height, height)

    media = ROOT / "media/war-outpost/packaged/ui"
    media.mkdir(parents=True, exist_ok=True)
    atlas.crop((0, 0, atlas.width, y + row_height + 2)).save(media / "outpost-labels.png", optimize=True)
    hud = ROOT / "src/game/apps/war-outpost/hud"
    lines = [f"  {key}: {json.dumps(frame, ensure_ascii=False)}" for key, frame in frames.items()]
    (hud / "labelFrames.ts").write_text(
        "/* Generated by scripts/build-outpost-labels.py. */\n"
        "export const labelFrames = {\n" + ",\n".join(lines) + "\n} as const;\n",
        encoding="utf-8",
    )


if __name__ == "__main__":
    main()
